'use strict';

/**
 * Bundle the user-facing guides into the renderer so first launch can drop
 * them into 笔记夹 on both desktop and Android. Sources stay plain Markdown.
 */

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const guides = [
  { name: '介绍.md', file: 'docs/介绍.md' },
  { name: '使用指南.md', file: 'docs/使用指南.md' },
  { name: '插件制作指导.md', file: '插件制作指导.md' },
  { name: '主题包制作指导.md', file: 'docs/主题包制作指导.md' }
];

const entries = guides.map((guide) => {
  const source = path.join(root, guide.file);
  if (!fs.existsSync(source)) throw new Error(`缺少指南文件：${guide.file}`);
  const content = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
  return { name: guide.name, content };
});

const banner = [
  '// Generated by scripts/build-guides.js — do not edit manually.',
  '// Sources: docs/介绍.md, docs/使用指南.md, 插件制作指导.md, docs/主题包制作指导.md'
].join('\n');
const output = `${banner}\nexport const bundledGuides = ${JSON.stringify(entries, null, 2)};\n`;
const target = path.join(root, 'src/renderer/guides.generated.js');
fs.writeFileSync(target, output, 'utf8');
console.log(`guides.generated.js: ${entries.length} docs, ${Buffer.byteLength(output)} bytes`);